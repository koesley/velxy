"""Tests for the landing page: public pricing, buy button, sample report.

The sample report is generated by the real report engine (automate.py) from
a small built-in sample dataset, so the asserted figures are the engine's
own output, not hand-written values. One test also serves the real HTTP
handler. Run with:
  python -m unittest test_landing_page -v
"""
import os
import tempfile
import threading
import unittest
import urllib.request
from http.server import ThreadingHTTPServer
from unittest.mock import patch

MAINNET_ENV = {
    'VELXTRIA_ENABLE_BTCPAY_MAINNET_CHECKOUT': '1',
    'VELXTRIA_BTCPAY_MAINNET_URL': 'https://btcpay.example.com',
    'VELXTRIA_BTCPAY_MAINNET_STORE_ID': 'store123',
    'VELXTRIA_BTCPAY_MAINNET_API_KEY': 'api-key-123',
}


class LandingPageTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.env = patch.dict(os.environ, {
            'VELXTRIA_DATA_DIR': self.tmp.name,
            'VELXTRIA_DEPLOYMENT_MODE': 'local',
            'VELXTRIA_ENABLE_BTCPAY_MAINNET_CHECKOUT': '0',
        })
        self.env.start()
        self.addCleanup(self.env.stop)
        self.addCleanup(self.tmp.cleanup)
        import portal
        self.portal = portal
        portal._SAMPLE_REPORT_HTML = None

    def test_public_navigation_is_focused_and_advanced_routes_remain_accessible(self):
        import re
        page = self.portal.shell('Home', self.portal.landing_page())
        nav = re.search(r'<nav\\b[^>]*class="velx-nav"[^>]*>(.*?)</nav>', page, re.S).group(1)
        primary_section = nav.split('<details class="velx-more">', 1)[0]
        primary = re.findall(r'class="velx-primary" href="([^"]+)"', primary_section)
        self.assertEqual(primary, ['/', '/business-os-v59', '/revenue-priority', '/account'])
        self.assertIn('<details class="velx-more">', nav)
        self.assertIn('href="/revenue-priority/live"', nav)
        self.assertIn('href="/revenue-followups"', nav)
        self.assertIn('href="/revenue-command"', nav)

    def test_pricing_free_and_pro(self):
        html = self.portal.landing_page()
        self.assertIn('FREE', html)
        self.assertIn('3 reports', html)
        self.assertIn('PRO', html)
        self.assertIn('$49', html)
        self.assertIn('50 reports', html)
        self.assertIn('Bitcoin', html)

    def test_logged_out_buy_goes_to_login_with_next(self):
        html = self.portal.landing_page()
        self.assertIn('Get PRO — $49 with Bitcoin', html)
        self.assertIn('/login?next=', html)
        self.assertNotIn('/btcpay/mainnet/checkout', html)

    def test_pro_interest_returns_to_pricing_after_login(self):
        html = self.portal.landing_buy_html(None, '')
        self.assertIn('/login?next=%2Faccount%23billing', html)
        self.assertIn('/register?next=%2Faccount%23billing', html)
        self.assertNotIn('/about', html)
        self.assertIn('verified payment', html)

    def test_demo_upsell_returns_to_pricing(self):
        result = {'monthly_rows': [['Month', 'Revenue']], 'product_rows': [['Product', 'Revenue']], 'stats': [], 'accepted': 0, 'rejected': 0}
        html = self.portal.demo_result_html(result, 'sample-token')
        self.assertIn('/login?next=%2Faccount%23billing', html)
        self.assertIn('Payment is optional', html)

    def test_account_billing_is_checkout_destination(self):
        import inspect
        handler_source = inspect.getsource(self.portal.Handler.do_GET)
        self.assertIn('id="billing"', handler_source)
        self.assertIn('action="/btcpay/mainnet/checkout"', handler_source)

    def test_logged_in_buy_posts_to_checkout_when_enabled(self):
        with patch.dict(os.environ, MAINNET_ENV):
            html = self.portal.landing_page({'id': 1, 'email': 'a@example.test'}, 'csrf-token')
        self.assertIn('action="/btcpay/mainnet/checkout"', html)
        self.assertIn('csrf-token', html)
        self.assertIn('Get PRO — $49 with Bitcoin', html)

    def test_logged_in_buy_disabled_when_checkout_off(self):
        html = self.portal.landing_page({'id': 1, 'email': 'a@example.test'}, 'csrf-token')
        self.assertIn('coming soon', html)
        self.assertNotIn('/btcpay/mainnet/checkout', html)

    def test_sample_report_uses_real_engine(self):
        html = self.portal.landing_page()
        self.assertIn('SAMPLE REPORT', html)
        self.assertIn('not a real business', html)
        # Figures produced by automate.py from the built-in sample dataset.
        self.assertIn('2026-10', html)
        self.assertIn('470.00', html)   # October paid revenue
        self.assertIn('330.00', html)   # November paid revenue
        self.assertIn('800.00', html)   # total paid revenue
        self.assertIn('Deep Cleaning', html)
        self.assertIn('Accepted rows: 6', html)
        self.assertIn('Rejected rows: 3', html)

    def test_sample_report_cached_and_escaped(self):
        first = self.portal.sample_report_html()
        second = self.portal.sample_report_html()
        self.assertEqual(first, second)
        self.assertNotIn('<script', first)

    def test_safe_next(self):
        self.assertEqual(self.portal.safe_next('/about'), '/about')
        self.assertEqual(self.portal.safe_next('/'), '/')
        self.assertEqual(self.portal.safe_next('https://evil.example.com'), '/')
        self.assertEqual(self.portal.safe_next('//evil.example.com'), '/')
        self.assertEqual(self.portal.safe_next(''), '/')
        self.assertEqual(self.portal.safe_next(None), '/')
        self.assertEqual(self.portal.safe_next('/\\\\evil.example/path'), '/')
        self.assertEqual(self.portal.safe_next('/%0a'), '/%0a')
        self.assertEqual(self.portal.safe_next('/safe\\nLocation: //evil.example'), '/')
        self.assertEqual(self.portal.safe_next('/safe\\r'), '/')
        self.assertEqual(self.portal.safe_next('/safe\\x7f'), '/')
        self.assertEqual(self.portal.safe_next('/safe?next=1'), '/safe?next=1')

    def test_get_root_returns_200_with_pricing_buy_and_sample(self):
        server = ThreadingHTTPServer(('127.0.0.1', 0), self.portal.Handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            with urllib.request.urlopen(
                    'http://127.0.0.1:%d/' % server.server_address[1], timeout=30) as resp:
                self.assertEqual(resp.status, 200)
                body = resp.read().decode('utf-8')
        finally:
            server.shutdown()
            server.server_close()
        self.assertIn('$49', body)
        self.assertIn('Get PRO — $49 with Bitcoin', body)
        self.assertIn('SAMPLE REPORT', body)
        self.assertIn('470.00', body)


if __name__ == '__main__':
    unittest.main()
